export function getArticle(slug: string): Article | undefined {
  return articles.find((a) => a.slug === slug);
}

export function listArticles(opts?: {
  category?: string;
  excludeSlug?: string;
  limit?: number;
}): Article[] {
  let list = [...articles].sort((a, b) =>
    a.publishedAt < b.publishedAt ? 1 : -1
  );
  if (opts?.category) list = list.filter((a) => a.category === opts.category);
  if (opts?.excludeSlug)
    list = list.filter((a) => a.slug !== opts.excludeSlug);
  if (opts?.limit) list = list.slice(0, opts.limit);
  return list;
}

export function getFeatured(): Article | undefined {
  return articles.find((a) => a.featured);
}
